export const DICTS = { en: EN, fr: FR };

let current = 'en';
try {
  const saved = localStorage.getItem('nkg.lang');
  current = saved === 'fr' || saved === 'en' ? saved : (navigator.language || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
} catch {
  current = (globalThis.navigator?.language || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}
if (typeof document !== 'undefined') document.documentElement.lang = current;

/** The language the app is shown in: 'fr' or 'en'. */
export const lang = () => current;
export function setLang(l) {
  current = l === 'fr' ? 'fr' : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
  try { localStorage.setItem('nkg.lang', current); } catch { /* storage blocked: keep it for this visit */ }
}
/** The text for a key in the current language; functions get the values. */
export function t(key, params = {}) {
  const v = DICTS[current][key] ?? EN[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(params) : v;
}
